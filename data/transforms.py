"""
Detection Augmentations
=======================
Geometric and photometric transforms operating on ``(image, boxes)`` pairs,
where boxes are xyxy in pixel coordinates of the accompanying image.

Letterbox padding is recorded as ``(ratio, pad)`` so predictions can be mapped
back to original image coordinates at evaluation time. Getting this inverse
wrong silently shifts every box and depresses mAP without any visible error,
so ``scale_boxes`` is the single implementation used everywhere.
"""

import math
import random

import cv2
import numpy as np


def letterbox(image, new_shape=640, color=(114, 114, 114), scaleup=True, stride=32):
    """Resize preserving aspect ratio, then pad to the target shape.

    Returns:
        image, ratio (rw, rh), pad (dw, dh)
    """
    if isinstance(new_shape, int):
        new_shape = (new_shape, new_shape)

    h, w = image.shape[:2]
    r = min(new_shape[0] / h, new_shape[1] / w)
    if not scaleup:
        r = min(r, 1.0)

    new_unpad = (int(round(w * r)), int(round(h * r)))
    dw = (new_shape[1] - new_unpad[0]) / 2
    dh = (new_shape[0] - new_unpad[1]) / 2

    if (w, h) != new_unpad:
        image = cv2.resize(image, new_unpad, interpolation=cv2.INTER_LINEAR)

    top, bottom = int(round(dh - 0.1)), int(round(dh + 0.1))
    left, right = int(round(dw - 0.1)), int(round(dw + 0.1))
    image = cv2.copyMakeBorder(image, top, bottom, left, right,
                               cv2.BORDER_CONSTANT, value=color)
    return image, (r, r), (dw, dh)


def scale_boxes(boxes, ratio, pad, orig_shape):
    """Map xyxy boxes from letterboxed space back to original image pixels.

    Args:
        boxes: [N, 4] xyxy in letterboxed coordinates
        ratio: (rw, rh) from ``letterbox``
        pad: (dw, dh) from ``letterbox``
        orig_shape: (h, w) of the source image
    """
    boxes = boxes.copy() if isinstance(boxes, np.ndarray) else boxes.clone()
    boxes[:, [0, 2]] -= pad[0]
    boxes[:, [1, 3]] -= pad[1]
    boxes[:, [0, 2]] /= ratio[0]
    boxes[:, [1, 3]] /= ratio[1]
    boxes[:, [0, 2]] = boxes[:, [0, 2]].clip(0, orig_shape[1])
    boxes[:, [1, 3]] = boxes[:, [1, 3]].clip(0, orig_shape[0])
    return boxes


def augment_hsv(image, h_gain=0.015, s_gain=0.7, v_gain=0.4):
    """Random hue/saturation/value shift via a lookup table (in place)."""
    if not (h_gain or s_gain or v_gain):
        return image
    gains = np.random.uniform(-1, 1, 3) * [h_gain, s_gain, v_gain] + 1
    hue, sat, val = cv2.split(cv2.cvtColor(image, cv2.COLOR_BGR2HSV))
    dtype = image.dtype

    x = np.arange(0, 256, dtype=gains.dtype)
    lut_hue = ((x * gains[0]) % 180).astype(dtype)
    lut_sat = np.clip(x * gains[1], 0, 255).astype(dtype)
    lut_val = np.clip(x * gains[2], 0, 255).astype(dtype)

    merged = cv2.merge((cv2.LUT(hue, lut_hue), cv2.LUT(sat, lut_sat),
                        cv2.LUT(val, lut_val)))
    return cv2.cvtColor(merged, cv2.COLOR_HSV2BGR)


def box_candidates(box1, box2, wh_thr=2, ar_thr=20, area_thr=0.1, eps=1e-16):
    """Filter boxes degenerated by a warp: too small, too thin, or mostly cropped."""
    w1, h1 = box1[2] - box1[0], box1[3] - box1[1]
    w2, h2 = box2[2] - box2[0], box2[3] - box2[1]
    ar = np.maximum(w2 / (h2 + eps), h2 / (w2 + eps))
    return (w2 > wh_thr) & (h2 > wh_thr) & \
           (w2 * h2 / (w1 * h1 + eps) > area_thr) & (ar < ar_thr)


def random_perspective(image, boxes, classes, degrees=0.0, translate=0.1,
                       scale=0.5, shear=0.0, perspective=0.0, border=(0, 0)):
    """Apply a random affine/perspective warp to image and boxes jointly.

    ``border`` is negative when undoing mosaic's doubled canvas.
    """
    height = image.shape[0] + border[0] * 2
    width = image.shape[1] + border[1] * 2

    # Center
    C = np.eye(3)
    C[0, 2] = -image.shape[1] / 2
    C[1, 2] = -image.shape[0] / 2

    P = np.eye(3)
    P[2, 0] = random.uniform(-perspective, perspective)
    P[2, 1] = random.uniform(-perspective, perspective)

    R = np.eye(3)
    a = random.uniform(-degrees, degrees)
    s = random.uniform(1 - scale, 1 + scale)
    R[:2] = cv2.getRotationMatrix2D(angle=a, center=(0, 0), scale=s)

    S = np.eye(3)
    S[0, 1] = math.tan(random.uniform(-shear, shear) * math.pi / 180)
    S[1, 0] = math.tan(random.uniform(-shear, shear) * math.pi / 180)

    T = np.eye(3)
    T[0, 2] = random.uniform(0.5 - translate, 0.5 + translate) * width
    T[1, 2] = random.uniform(0.5 - translate, 0.5 + translate) * height

    M = T @ S @ R @ P @ C
    if border[0] or border[1] or (M != np.eye(3)).any():
        if perspective:
            image = cv2.warpPerspective(image, M, dsize=(width, height),
                                        borderValue=(114, 114, 114))
        else:
            image = cv2.warpAffine(image, M[:2], dsize=(width, height),
                                   borderValue=(114, 114, 114))

    n = len(boxes)
    if n == 0:
        return image, boxes, classes

    # Warp all four corners, then take the axis-aligned hull. Using only two
    # corners would shrink boxes under rotation.
    xy = np.ones((n * 4, 3))
    xy[:, :2] = boxes[:, [0, 1, 2, 3, 0, 3, 2, 1]].reshape(n * 4, 2)
    xy = xy @ M.T
    xy = (xy[:, :2] / xy[:, 2:3] if perspective else xy[:, :2]).reshape(n, 8)

    x = xy[:, [0, 2, 4, 6]]
    y = xy[:, [1, 3, 5, 7]]
    new = np.concatenate((x.min(1), y.min(1), x.max(1), y.max(1))).reshape(4, n).T
    new[:, [0, 2]] = new[:, [0, 2]].clip(0, width)
    new[:, [1, 3]] = new[:, [1, 3]].clip(0, height)

    keep = box_candidates(box1=boxes.T * s, box2=new.T, area_thr=0.1)
    return image, new[keep], classes[keep]


def mosaic4(images, boxes_list, classes_list, img_size, border_ratio=0.5):
    """Combine four images into one 2x-canvas mosaic.

    Mosaic is the highest-value augmentation for detection: it multiplies the
    object count per training image, forces the model to handle objects at
    positions and scales that do not occur naturally, and provides abundant
    context-free negatives at image borders.
    """
    s = img_size
    border = (-int(s * border_ratio), -int(s * border_ratio))
    yc = int(random.uniform(s * border_ratio, 2 * s - s * border_ratio))
    xc = int(random.uniform(s * border_ratio, 2 * s - s * border_ratio))

    canvas = np.full((s * 2, s * 2, 3), 114, dtype=np.uint8)
    out_boxes, out_classes = [], []

    for i, (img, boxes, classes) in enumerate(zip(images, boxes_list, classes_list)):
        h, w = img.shape[:2]
        r = min(s / h, s / w)
        if r != 1:
            img = cv2.resize(img, (int(w * r), int(h * r)), interpolation=cv2.INTER_LINEAR)
            h, w = img.shape[:2]

        if i == 0:      # top-left
            x1a, y1a, x2a, y2a = max(xc - w, 0), max(yc - h, 0), xc, yc
            x1b, y1b, x2b, y2b = w - (x2a - x1a), h - (y2a - y1a), w, h
        elif i == 1:    # top-right
            x1a, y1a, x2a, y2a = xc, max(yc - h, 0), min(xc + w, s * 2), yc
            x1b, y1b, x2b, y2b = 0, h - (y2a - y1a), min(w, x2a - x1a), h
        elif i == 2:    # bottom-left
            x1a, y1a, x2a, y2a = max(xc - w, 0), yc, xc, min(s * 2, yc + h)
            x1b, y1b, x2b, y2b = w - (x2a - x1a), 0, w, min(y2a - y1a, h)
        else:           # bottom-right
            x1a, y1a, x2a, y2a = xc, yc, min(xc + w, s * 2), min(s * 2, yc + h)
            x1b, y1b, x2b, y2b = 0, 0, min(w, x2a - x1a), min(y2a - y1a, h)

        canvas[y1a:y2a, x1a:x2a] = img[y1b:y2b, x1b:x2b]
        pad_w, pad_h = x1a - x1b, y1a - y1b

        if len(boxes):
            b = boxes.copy() * r
            b[:, [0, 2]] += pad_w
            b[:, [1, 3]] += pad_h
            out_boxes.append(b)
            out_classes.append(classes)

    if out_boxes:
        out_boxes = np.concatenate(out_boxes, 0)
        out_classes = np.concatenate(out_classes, 0)
        np.clip(out_boxes, 0, 2 * s, out=out_boxes)
    else:
        out_boxes = np.zeros((0, 4), dtype=np.float32)
        out_classes = np.zeros((0,), dtype=np.int64)

    return canvas, out_boxes, out_classes, border


def mixup(image1, boxes1, classes1, image2, boxes2, classes2, alpha=32.0):
    """Blend two images and concatenate their labels."""
    ratio = np.random.beta(alpha, alpha)
    image = (image1 * ratio + image2 * (1 - ratio)).astype(np.uint8)
    boxes = np.concatenate((boxes1, boxes2), 0)
    classes = np.concatenate((classes1, classes2), 0)
    return image, boxes, classes


def xyxy2xywhn(boxes, w, h, clip=True, eps=1e-3):
    """xyxy pixels -> normalized cxcywh, dropping degenerate boxes."""
    if len(boxes) == 0:
        return boxes.reshape(0, 4)
    if clip:
        boxes[:, [0, 2]] = boxes[:, [0, 2]].clip(0, w - eps)
        boxes[:, [1, 3]] = boxes[:, [1, 3]].clip(0, h - eps)
    out = np.empty_like(boxes)
    out[:, 0] = ((boxes[:, 0] + boxes[:, 2]) / 2) / w
    out[:, 1] = ((boxes[:, 1] + boxes[:, 3]) / 2) / h
    out[:, 2] = (boxes[:, 2] - boxes[:, 0]) / w
    out[:, 3] = (boxes[:, 3] - boxes[:, 1]) / h
    return out


def xywhn2xyxy(boxes, w, h):
    """Normalized cxcywh -> xyxy pixels."""
    out = np.empty_like(boxes)
    out[:, 0] = (boxes[:, 0] - boxes[:, 2] / 2) * w
    out[:, 1] = (boxes[:, 1] - boxes[:, 3] / 2) * h
    out[:, 2] = (boxes[:, 0] + boxes[:, 2] / 2) * w
    out[:, 3] = (boxes[:, 1] + boxes[:, 3] / 2) * h
    return out
